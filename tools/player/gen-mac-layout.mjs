#!/usr/bin/env node
// Generate the Swift ANSI-104 key table for apps/player-mac from the shared
// @rgbprompt/layouts data. The table is written in ANSI104_KEYS order, which is
// the order of the 104 x 3 bytes returned by rgbp_preview_frame.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { ANSI104_KEYS } from '../../packages/layouts/src/ansi104.ts';
import { ANSI104_KLE } from '../../packages/layouts/src/data.ts';
import { parseKLE } from '../../packages/layouts/src/kle.ts';
import { semanticKeyName } from '../../packages/layouts/src/keyboard.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = resolve(ROOT, 'apps/player-mac/Sources/PlayerKit/Generated/KeyLayout.swift');

function geometryByKeyName() {
  const keys = parseKLE(ANSI104_KLE);
  const byName = new Map();
  for (const key of keys) {
    const parts = key.label.split('\n');
    key.legendTop = parts.length > 1 ? parts[0] : '';
    key.legendBottom = parts.length > 1 ? parts[1] : parts[0];
    const name = semanticKeyName(key);
    if (!name) throw new Error(`no ANSI104 name for KLE key ${JSON.stringify(key.label)}`);
    if (byName.has(name)) throw new Error(`duplicate ANSI104 name ${name}`);
    byName.set(name, key);
  }
  return byName;
}

function number(value) {
  return Number.isInteger(value) ? String(value) : String(value);
}

function render() {
  const byName = geometryByKeyName();
  let maxX = 0;
  let maxY = 0;
  const rows = [];
  for (const name of ANSI104_KEYS) {
    const key = byName.get(name);
    if (!key) throw new Error(`ANSI104_KEYS entry ${name} is missing from the KLE layout`);
    maxX = Math.max(maxX, key.x + key.w);
    maxY = Math.max(maxY, key.y + key.h);
    rows.push(
      `        .init(name: ${JSON.stringify(name)}, x: ${number(key.x)}, y: ${number(key.y)}, w: ${number(key.w)}, h: ${number(key.h)}),`,
    );
  }
  return `// Generated by tools/player/gen-mac-layout.mjs. Do not edit by hand.
// Geometry is in key units; the order matches ANSI104_KEYS and the 312 bytes
// returned by rgbp_preview_frame.

public struct KeyGeometry: Equatable, Sendable {
    public let name: String
    public let x: Double
    public let y: Double
    public let w: Double
    public let h: Double
}

public enum KeyLayout {
    public static let maxX: Double = ${number(maxX)}
    public static let maxY: Double = ${number(maxY)}

    public static let keys: [KeyGeometry] = [
${rows.join('\n')}
    ]
}
`;
}

const expected = render();
const check = process.argv.includes('--check');

if (check) {
  let actual = '';
  try {
    actual = readFileSync(OUT, 'utf8');
  } catch {
    console.error(`player:mac:layout: missing ${OUT}`);
    process.exit(1);
  }
  if (actual !== expected) {
    console.error('player:mac:layout: generated key layout is out of date');
    console.error('player:mac:layout: run `pnpm player:mac:layout` to regenerate it');
    process.exit(1);
  }
  console.log(`player:mac:layout: ${ANSI104_KEYS.length} keys up to date`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, expected);
  console.log(`player:mac:layout: wrote ${ANSI104_KEYS.length} keys to ${OUT}`);
}
