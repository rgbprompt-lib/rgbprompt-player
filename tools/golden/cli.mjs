// Golden-frame CLI: verify, update, cadence reports and coverage.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { decode, encode, normalize } from '@rgbprompt/engine';

import { buildCorpus } from './corpus.mjs';
import {
  CADENCE_FILE,
  VECTORS_DIR,
  cadenceForCase,
  firstCrcDifference,
  formatVector,
  readExemptCases,
  vectorFor,
  vectorForProgram,
  vectorPath,
} from './lib.mjs';

const COLUMNS = ['no-input 20v40', 'no-input 20v33', 'input 20v40', 'input 20v33'];

function readVector(caseId) {
  const path = vectorPath(caseId);
  if (!existsSync(path)) return null;
  return JSON.parse(readFileSync(path, 'utf8'));
}

function writeFile(path, contents) {
  writeFileSync(path, contents, 'utf8');
}

function staleVectorIds(expectedIds) {
  const expected = new Set(expectedIds);
  return readdirSync(fileURLToPath(VECTORS_DIR))
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.replace(/\.json$/, ''))
    .filter((id) => !expected.has(id));
}

function verify() {
  const corpus = buildCorpus();
  let totalFrames = 0;
  let failures = 0;
  let roundtripOk = 0;

  for (const entry of corpus) {
    const actual = vectorFor(entry.effect, entry.inputs);
    totalFrames += actual.frames;
    const expected = readVector(entry.id);
    if (!expected) {
      console.error(`golden: ${entry.id}: vector is missing (run golden:update)`);
      failures++;
      continue;
    }
    if (expected.engine !== actual.engine) {
      console.error(
        `golden: ${entry.id}: engine changed from ${expected.engine} to ${actual.engine} (run golden:update)`,
      );
      failures++;
    }
    const first = firstCrcDifference(expected.crc32 || [], actual.crc32);
    if (first !== -1) {
      const tick = first * actual.stepMs;
      console.error(
        `golden: ${entry.id}: first differing frame ${first} at t=${tick} ms ` +
          `(expected ${expected.crc32?.[first] ?? 'missing'}, got ${actual.crc32[first] ?? 'missing'})`,
      );
      failures++;
      continue;
    }
    if (expected.sha256 !== actual.sha256) {
      console.error(`golden: ${entry.id}: sha256 differs (run golden:update)`);
      failures++;
      continue;
    }

    const decoded = decode(encode(normalize(entry.effect)));
    const roundtrip = vectorForProgram(decoded.program, entry.inputs);
    const roundtripFirst = firstCrcDifference(expected.crc32 || [], roundtrip.crc32);
    if (roundtripFirst !== -1 || expected.sha256 !== roundtrip.sha256) {
      const detail =
        roundtripFirst === -1
          ? 'sha256 differs'
          : `first differing frame ${roundtripFirst} at t=${roundtripFirst * roundtrip.stepMs} ms`;
      console.error(`golden: ${entry.id}: .lep round trip changed the frames (${detail})`);
      failures++;
      continue;
    }
    roundtripOk++;
  }

  if (failures > 0) {
    console.error(`golden: ${failures} case(s) failed`);
    process.exitCode = 1;
    return;
  }
  console.log(
    `golden: ok (${corpus.length} cases, ${totalFrames} frames; round trip ${roundtripOk}/${corpus.length})`,
  );
}

function update() {
  const corpus = buildCorpus();
  mkdirSync(fileURLToPath(VECTORS_DIR), { recursive: true });
  let totalFrames = 0;
  for (const entry of corpus) {
    const vector = vectorFor(entry.effect, entry.inputs);
    totalFrames += vector.frames;
    writeFile(vectorPath(entry.id), formatVector(vector));
  }
  for (const id of staleVectorIds(corpus.map((entry) => entry.id))) {
    unlinkSync(fileURLToPath(vectorPath(id)));
  }
  console.log(`golden: updated (${corpus.length} cases, ${totalFrames} frames)`);
}

function cadenceMarkdown(rows) {
  const headers = ['case', ...COLUMNS];
  const widths = headers.map((header, index) =>
    Math.max(
      header.length,
      ...rows.map((row) => String(index === 0 ? row.id : row[COLUMNS[index - 1]]).length),
    ),
  );
  const formatRow = (cells) =>
    `| ${cells.map((cell, index) => String(cell).padEnd(widths[index])).join(' | ')} |`;
  const lines = [
    '# Cadence invariance report',
    '',
    'Generated by `corepack pnpm golden:cadence`. Do not edit by hand.',
    '',
    'A cell is `ok` when every common tick has byte-identical frames, otherwise it shows `diff k/n`.',
    'Ticks are compared at multiples of 40 ms (20 vs 40, 250 frames) and 660 ms (20 vs 33, 16 frames).',
    '',
    formatRow(headers),
    `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`,
  ];
  for (const row of rows) {
    lines.push(formatRow([row.id, ...COLUMNS.map((column) => row[column])]));
  }
  const differing = rows.filter((row) => COLUMNS.some((column) => row[column] !== 'ok')).length;
  lines.push('', `Cases with any difference: ${differing} of ${rows.length}.`, '');
  return lines.join('\n');
}

function cadence(strict) {
  const corpus = buildCorpus();
  const rows = corpus.map((entry) => ({
    id: entry.id,
    ...cadenceForCase(entry.effect, entry.inputs),
  }));
  writeFile(CADENCE_FILE, cadenceMarkdown(rows));
  const differing = rows.filter((row) => COLUMNS.some((column) => row[column] !== 'ok')).length;
  console.log(`golden: cadence report written (${rows.length} cases, ${differing} with differences)`);

  if (!strict) return;
  const exempt = new Set(readExemptCases());
  const byId = new Map(rows.map((row) => [row.id, row]));
  let failed = 0;
  for (const id of exempt) {
    if (!byId.has(id)) {
      console.error(`golden: cadence strict: ${id}: unknown case in cadence-exempt.json`);
      failed++;
    }
  }
  for (const row of rows) {
    if (exempt.has(row.id)) continue;
    const bad = COLUMNS.filter((column) => row[column] !== 'ok');
    if (bad.length > 0) {
      console.error(
        `golden: cadence strict: ${row.id}: ${bad.map((column) => `${column}=${row[column]}`).join(', ')}`,
      );
      failed++;
    }
  }
  if (failed > 0) {
    console.error(`golden: cadence strict: ${failed} case(s) are not invariant`);
    process.exitCode = 1;
  }
}

const COVERAGE_FILES = ['render.ts', 'color.ts', 'surfaces.ts', 'timing.ts'];
const COVERAGE_TARGETS = {
  'render.ts': { line: 97, branch: 93 },
  'color.ts': { line: 90 },
  'surfaces.ts': { line: 90 },
  'timing.ts': { line: 90 },
};
const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));

function parseCoverage(output) {
  const rows = new Map();
  const pattern = /([\w.-]+\.(?:js|ts))\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|\s*(.*)$/;
  for (const line of output.split('\n')) {
    const match = pattern.exec(line.replace(/^#\s*/, ''));
    if (!match || !COVERAGE_FILES.includes(match[1])) continue;
    rows.set(match[1], {
      line: Number(match[2]),
      branch: Number(match[3]),
      funcs: Number(match[4]),
      uncovered: match[5].trim(),
    });
  }
  return rows;
}

function coverage() {
  const runner = fileURLToPath(new URL('./coverage-runner.mjs', import.meta.url));
  const includes = COVERAGE_FILES.map((file) => `--test-coverage-include=packages/engine/src/${file}`);
  const result = spawnSync(
    process.execPath,
    ['--test', '--experimental-test-coverage', ...includes, runner],
    { cwd: REPO_ROOT, encoding: 'utf8' },
  );
  const output = `${result.stdout || ''}${result.stderr || ''}`;
  const rows = parseCoverage(output);
  if (rows.size !== COVERAGE_FILES.length) {
    console.error(output);
    console.error('golden: coverage: could not parse the coverage report');
    process.exitCode = 1;
    return;
  }

  const headers = ['file', 'line %', 'branch %', 'uncovered lines', 'target'];
  const table = COVERAGE_FILES.map((file) => {
    const row = rows.get(file);
    const target = COVERAGE_TARGETS[file];
    const failures = [];
    if (row.line < target.line) failures.push(`line ${row.line} < ${target.line}`);
    if (target.branch !== undefined && row.branch < target.branch) {
      failures.push(`branch ${row.branch} < ${target.branch}`);
    }
    return {
      cells: [
        file,
        row.line.toFixed(2),
        row.branch.toFixed(2),
        row.uncovered || '-',
        target.branch === undefined ? `line ${target.line}` : `line ${target.line}, branch ${target.branch}`,
      ],
      failures,
    };
  });
  const widths = headers.map((header, index) =>
    Math.max(header.length, ...table.map((row) => row.cells[index].length)),
  );
  const formatRow = (cells) =>
    `| ${cells.map((cell, index) => String(cell).padEnd(widths[index])).join(' | ')} |`;
  console.log(formatRow(headers));
  console.log(`| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`);
  for (const row of table) console.log(formatRow(row.cells));

  const failed = table.filter((row) => row.failures.length > 0);
  if (failed.length > 0) {
    for (const row of failed) {
      console.error(`golden: coverage: ${row.cells[0]}: ${row.failures.join(', ')}`);
    }
    process.exitCode = 1;
    return;
  }
  console.log('golden: coverage targets met');
}

const [command = 'verify', ...flags] = process.argv.slice(2);

switch (command) {
  case 'verify':
    verify();
    break;
  case 'update':
    update();
    break;
  case 'cadence':
    cadence(flags.includes('--strict'));
    break;
  case 'coverage':
    coverage();
    break;
  default:
    console.error(`golden: unknown command "${command}" (expected verify, update, cadence or coverage)`);
    process.exitCode = 1;
}
